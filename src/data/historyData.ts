export function getAllHistoryItems(): HistoryItem[] {
  const items: HistoryItem[] = [];
  for (const section of HISTORY_SECTIONS) {
    items.push(...section.items);
  }
  return items;
}

export function getChronologicalHistory(): HistoryItem[] {
  return [...getAllHistoryItems()].sort((a, b) => a.numericYear - b.numericYear);
}
